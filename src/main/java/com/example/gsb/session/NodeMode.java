package com.example.gsb.session;

/**
 * 节点（服务实例）的会话路由模式。
 */
public enum NodeMode {

    /**
     * 粘性模式：同一会话的请求由负载均衡始终路由到同一节点，节点可使用本地缓存
     * （低延迟）。一致性依赖路由粘性；一旦会话被别的节点修改，本节点缓存会变陈旧，
     * 因此要求路由在会话存活期间保持稳定，必要时通过失效消息/重新路由刷新缓存。
     */
    STICKY,

    /**
     * 非粘性模式：请求可落到任意节点，每次读取都直接访问共享存储，
     * 因此任何节点都能读到最新的已提交完整版本（强一致），代价是无本地缓存加速。
     */
    NON_STICKY
}
